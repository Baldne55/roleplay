/**
 * Weapon-domain item catalog: every holdable weapon model from the
 * FiveM weapon-models reference, the attachable (non-default)
 * components of those weapons, ammunition per ammo class, and the
 * forensic shell-casing drops.
 *
 * Identity data - weapon hashes, component hashes, attach-slot
 * grouping, English labels, component descriptions - is extracted
 * from game data; every hash literal below is the lowercase joaat of
 * the canonical R* name in the adjacent comment, computationally
 * verified at generation time (the engine silently discards an
 * unrecognised hash, so a fabricated literal is a silent no-op).
 * Weights, clip sizes, burst caps, and stack caps are server balance
 * values - tune freely. Clip sizes were reconciled against
 * GET_WEAPON_CLIP_SIZE through /aitem testcatalog on game build 3751;
 * engine belt/charge sentinels are deliberately not adopted (minigun +
 * rayminigun report 15000, raycarbine 9999, stungun 100000) - those
 * weapons keep curated reload caps.
 *
 * Throwables are their own ammunition (IsThrowable): equip arms the
 * ped with the row's StackQuantity and every throw consumes one. The
 * utility cans + extinguisher spawn with a full charge (DefaultAmmo
 * seeds a self-typed LoadedAmmo segment at creation) and drain through
 * the discharge accounting; refill mechanics are a later slice.
 *
 * Deliberately excluded:
 *   - WEAPON_UNARMED (the empty-hands state, not an item)
 *   - COMPONENT_GUNRUN_MK2_UPGRADE (workbench conversion token;
 *     attaching it standalone is a silent no-op)
 *
 * Attachment slots mirror the engine attach-bone families, so two
 * components that exclude each other in-game land in the same slot:
 * WAPClip -> Magazine, WAPScop -> Sight, WAPSupp -> Muzzle (brakes +
 * compensators included), WAPGrip -> Grip, WAPFlshLasr -> Flashlight,
 * WAPBarrel -> Barrel, gun_root -> Skin.
 */

